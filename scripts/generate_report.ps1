# SlickDesk - Auto Report Generator
# Run this script to generate a daily ticket summary report

$dbPath = "../database/slickdesk.db"
$reportPath = "./reports"
$date = Get-Date -Format "yyyy-MM-dd"
$reportFile = "$reportPath/report_$date.txt"

# Create reports folder if it doesn't exist
if (-not (Test-Path $reportPath)) {
    New-Item -ItemType Directory -Path $reportPath | Out-Null
}

Write-Host "=====================================" -ForegroundColor Cyan
Write-Host "  SlickDesk Daily Report - $date" -ForegroundColor Cyan
Write-Host "=====================================" -ForegroundColor Cyan

# Check if sqlite3 is available
if (Get-Command sqlite3 -ErrorAction SilentlyContinue) {
    $total     = sqlite3 $dbPath "SELECT COUNT(*) FROM tickets;"
    $open      = sqlite3 $dbPath "SELECT COUNT(*) FROM tickets WHERE status='Open';"
    $resolved  = sqlite3 $dbPath "SELECT COUNT(*) FROM tickets WHERE status='Resolved';"
    $critical  = sqlite3 $dbPath "SELECT COUNT(*) FROM tickets WHERE priority='Critical';"
    $assets    = sqlite3 $dbPath "SELECT COUNT(*) FROM assets;"

    $report = @"
SlickDesk Daily Report
Date: $date
==============================
Total Tickets  : $total
Open Tickets   : $open
Resolved       : $resolved
Critical       : $critical
Total Assets   : $assets
==============================
Generated by SlickDesk Automation Script
"@

    $report | Out-File -FilePath $reportFile
    Write-Host $report
    Write-Host "`nReport saved to: $reportFile" -ForegroundColor Green
} else {
    Write-Host "sqlite3 not found. Please install it to run this script." -ForegroundColor Red
    Write-Host "Sample report structure saved instead." -ForegroundColor Yellow

    $sampleReport = @"
SlickDesk Daily Report
Date: $date
==============================
Total Tickets  : [connect to DB]
Open Tickets   : [connect to DB]
Resolved       : [connect to DB]
Critical       : [connect to DB]
Total Assets   : [connect to DB]
==============================
"@
    $sampleReport | Out-File -FilePath $reportFile
}
